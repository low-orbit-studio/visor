#!/usr/bin/env node
/**
 * generate-private-themes.mjs
 *
 * Build-time generator that materializes per-theme CSS and a manifest from
 * `@low-orbit-studio/visor-themes-private`. Runs as `predev` and `prebuild`.
 *
 * When the package is installed (consumer has GITHUB_PACKAGES_TOKEN with
 * read:packages access), iterates `listThemes()` and emits:
 *   - app/private-themes.generated.css   — one block per theme, scoped to `.{slug}-theme`
 *   - lib/private-themes.generated.ts    — `export const PRIVATE_THEMES = [...]`
 *
 * When the package is not installed but a local `visor-themes-private/themes/`
 * checkout is reachable (Low Orbit dev machines — VISOR_THEMES_PRIVATE_PATH,
 * a true sibling, or the `~/Code/low-orbit/` parent-glob convention that
 * `visor theme sync` also uses), materializes from that checkout instead.
 *
 * When neither the package nor a local checkout is available (public
 * self-hosters, no token), writes empty stubs so the build continues. The
 * /themes/private route reads the empty manifest and returns 404.
 *
 * Idempotent — safe to run repeatedly.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs"
import { resolve, dirname, join, sep } from "node:path"
import { fileURLToPath } from "node:url"
import { spawnSync, execFileSync } from "node:child_process"
import { extractTypographySlots } from "./extract-typography-slots.mjs"

const PRIVATE_PKG = "@low-orbit-studio/visor-themes-private"
const PRIVATE_THEMES_ENV_VAR = "VISOR_THEMES_PRIVATE_PATH"

const __dirname = dirname(fileURLToPath(import.meta.url))
const docsRoot = resolve(__dirname, "..")
const cssOutPath = resolve(docsRoot, "app", "private-themes.generated.css")
const tsOutPath = resolve(docsRoot, "lib", "private-themes.generated.ts")
// VI-489: private brand SVGs are copied here so `source: local` brand paths
// (`/themes/{slug}/brand/*.svg`) resolve at runtime. Gitignored — never
// committed to the public Visor repo.
const publicThemesDir = resolve(docsRoot, "public", "themes")

const EMPTY_CSS = "/* generated by scripts/generate-private-themes.mjs — empty when @low-orbit-studio/visor-themes-private is not installed */\n"
const EMPTY_TS = `import type { PrivateThemeEntry } from "./private-themes";\nexport const PRIVATE_THEMES: PrivateThemeEntry[] = [];\n`

function toLabel(slug) {
  return slug
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ")
}

/**
 * Copy a private theme's local brand SVGs into the docs public dir so the
 * `source: local` paths declared in its `brand:` block resolve at runtime.
 * Returns true when a `brand/` directory shipped at least one SVG. The brand
 * dir lives alongside the theme YAML in the private checkout / package
 * (`{slug}/theme.visor.yaml` + `{slug}/brand/`). Copied assets are gitignored.
 */
function copyBrandAssets(themeFilePath, slug) {
  const brandSrcDir = join(dirname(themeFilePath), "brand")
  if (!existsSync(brandSrcDir)) return false
  const destDir = join(publicThemesDir, slug, "brand")
  mkdirSync(destDir, { recursive: true })
  let copied = 0
  for (const file of readdirSync(brandSrcDir)) {
    if (!file.endsWith(".svg")) continue
    copyFileSync(join(brandSrcDir, file), join(destDir, file))
    copied++
  }
  return copied > 0
}

/**
 * Map a theme-engine `resolveThemeBrand` result to the docs `ThemeBrand` shape
 * (lib/theme-config.ts). The engine returns only the variants a theme actually
 * declares, so any missing standard slot — `monochrome` in particular, which
 * BO-47's private themes omit — falls back to the resolved Visor default mark
 * (D2). `animated` is optional and emitted only when the theme declares it.
 */
function toDocsBrand(themeVariants, defaultVariants) {
  const by = Object.fromEntries(themeVariants.map((v) => [v.variant, v]))
  const def = Object.fromEntries(defaultVariants.map((v) => [v.variant, v]))
  const pick = (variant) => by[variant] ?? def[variant]
  const asset = (v) => ({ light: v.light, dark: v.dark })
  const brand = {
    logo: asset(pick("logo")),
    brandmark: asset(pick("brandmark")),
    wordmark: asset(pick("wordmark")),
    monochrome: pick("monochrome").light,
  }
  if (by.animated) brand.animated = asset(by.animated)
  return brand
}

function writeEmpty(reason) {
  mkdirSync(dirname(cssOutPath), { recursive: true })
  mkdirSync(dirname(tsOutPath), { recursive: true })
  writeFileSync(cssOutPath, EMPTY_CSS, "utf-8")
  writeFileSync(tsOutPath, EMPTY_TS, "utf-8")
  console.log(`[generate-private-themes] empty stubs written (${reason})`)
}

function tryInstallPrivatePackage() {
  // Install on-the-fly when the token is set. We deliberately avoid declaring
  // the package as an optionalDependency in package.json — npm in workspace
  // mode struggles to lockfile a missing optional package cleanly, and the
  // resulting stub entry breaks subsequent `npm install` invocations on Vercel.
  // Installing here with --no-save keeps package.json/package-lock.json clean.
  if (!process.env.GITHUB_PACKAGES_TOKEN) {
    return false
  }
  console.log(`[generate-private-themes] GITHUB_PACKAGES_TOKEN present — installing ${PRIVATE_PKG}@latest`)
  // --include=dev: Vercel sets NODE_ENV=production during the build, which would
  // make `npm install` prune devDependencies (typescript, @types/*). Force dev
  // deps to stay so the next-build step that follows still has its toolchain.
  const result = spawnSync(
    "npm",
    ["install", "--no-save", "--include=dev", `${PRIVATE_PKG}@latest`],
    { cwd: docsRoot, stdio: "inherit", env: process.env },
  )
  if (result.status !== 0) {
    console.warn(`[generate-private-themes] npm install of ${PRIVATE_PKG} failed (exit ${result.status}) — falling back to empty stubs`)
    return false
  }
  return true
}

/**
 * Resolve the canonical main checkout's repo root. In a git worktree,
 * `--git-common-dir` points at the main checkout's `.git`, so its parent is the
 * main repo. Mirrors `findMainRepoRoot` in packages/cli — sibling lookups must
 * converge to the same `visor-themes-private/` regardless of which worktree
 * the generator runs from. Falls back to the docs repo root (two levels up
 * from packages/docs) when git is unavailable.
 */
function findMainRepoRoot() {
  const repoRootFromDocs = resolve(docsRoot, "..", "..")
  try {
    const commonDir = execFileSync("git", ["rev-parse", "--git-common-dir"], {
      cwd: docsRoot,
      encoding: "utf-8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim()
    if (commonDir) {
      const candidate = dirname(resolve(docsRoot, commonDir))
      if (existsSync(join(candidate, "packages", "docs"))) return candidate
    }
  } catch {
    // git not available — fall through to the docs-relative root
  }
  return repoRootFromDocs
}

/**
 * Scan `parentDir` one level deep for any `<dir>/visor-themes-private/themes/`
 * directory. Mirrors `scanParentForPrivateThemes` in packages/cli — catches the
 * LO convention `~/Code/low-orbit/visor-themes-private/themes/` when the visor
 * checkout is at `~/Code/visor/`. Returns absolute paths sorted alphabetically.
 */
function scanParentForPrivateThemes(parentDir) {
  if (!existsSync(parentDir)) return []
  const matches = []
  for (const entry of readdirSync(parentDir, { withFileTypes: true })) {
    if (!entry.isDirectory() && !entry.isSymbolicLink()) continue
    const candidate = join(parentDir, entry.name, "visor-themes-private", "themes")
    if (existsSync(candidate)) matches.push(candidate)
  }
  return matches.sort()
}

/**
 * Locate a local private-themes `themes/` directory using the same precedence
 * as `visor theme sync` (packages/cli/src/commands/theme-sync.ts):
 *   1. VISOR_THEMES_PRIVATE_PATH env var (points at the package root or themes/)
 *   2. true sibling — `<main-repo>/../visor-themes-private/themes/`
 *   3. parent-glob — `<main-repo>/../<any-dir>/visor-themes-private/themes/`
 * Returns the absolute path to a `{slug}/theme.visor.yaml` layout, or null.
 */
function findLocalThemesDir() {
  const envPath = process.env[PRIVATE_THEMES_ENV_VAR]
  if (envPath && envPath.trim() !== "") {
    const resolved = resolve(envPath)
    // Accept either the package root (…/themes lives under it) or themes/ itself.
    const withThemes = join(resolved, "themes")
    if (existsSync(withThemes)) return withThemes
    if (existsSync(resolved)) return resolved
  }

  const mainRepoRoot = findMainRepoRoot()
  const siblingPath = join(mainRepoRoot, "..", "visor-themes-private", "themes")
  if (existsSync(siblingPath)) return siblingPath

  const parentDir = join(mainRepoRoot, "..")
  // Defensive: never pick a stray checkout placed inside the Visor repo itself.
  const matches = scanParentForPrivateThemes(parentDir).filter(
    (path) => !path.startsWith(mainRepoRoot + sep),
  )
  return matches.length > 0 ? matches[0] : null
}

/**
 * Build a source object matching the @low-orbit-studio/visor-themes-private
 * package API (`listThemes`/`readTheme`/`themePath`) from a local `themes/`
 * directory laid out as `{slug}/theme.visor.yaml`. Lets `main()` consume the
 * local checkout and the installed npm package through one interface.
 */
function localPrivateSource(themesDir) {
  const slugs = readdirSync(themesDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() || e.isSymbolicLink())
    .map((e) => e.name)
    .filter((slug) => existsSync(join(themesDir, slug, "theme.visor.yaml")))
  return {
    listThemes: () => slugs,
    themePath: (slug) => join(themesDir, slug, "theme.visor.yaml"),
    readTheme: (slug) => readFileSync(join(themesDir, slug, "theme.visor.yaml"), "utf-8"),
  }
}

async function main() {
  let pkg
  try {
    pkg = await import(PRIVATE_PKG)
  } catch {
    if (tryInstallPrivatePackage()) {
      try {
        pkg = await import(PRIVATE_PKG)
      } catch (err) {
        console.warn(`[generate-private-themes] import after install failed: ${err.message}`)
        writeEmpty("import failed after install")
        return
      }
    } else {
      // Package not installed (no GITHUB_PACKAGES_TOKEN). On a Low Orbit dev
      // machine the themes live in a sibling checkout — resolve them the same
      // way `visor theme sync` does (env var → sibling → parent-glob) so the
      // /themes/private gallery renders locally without publishing to npm.
      const themesDir = findLocalThemesDir()
      if (themesDir) {
        console.log(`[generate-private-themes] using local private themes at ${themesDir}`)
        pkg = localPrivateSource(themesDir)
      } else {
        writeEmpty("package not installed and no local themes checkout found")
        return
      }
    }
  }

  let engine, adapters
  try {
    engine = await import("@loworbitstudio/visor-theme-engine")
    adapters = await import("@loworbitstudio/visor-theme-engine/adapters")
  } catch (err) {
    console.error(`[generate-private-themes] theme-engine import failed: ${err.message}`)
    process.exit(1)
  }

  const slugs = pkg.listThemes()
  if (slugs.length === 0) {
    writeEmpty("package installed but exports zero themes")
    return
  }

  const cssBlocks = []
  const manifest = []
  const importLines = new Set()
  // VI-489: resolved Visor default brand — fills any standard slot a private
  // theme omits (e.g. monochrome) when mapping to the docs ThemeBrand shape.
  const defaultBrandVariants = engine.resolveThemeBrand(undefined).variants

  for (const slug of slugs) {
    let yamlContent
    try {
      yamlContent = pkg.readTheme(slug)
    } catch (err) {
      console.error(`[generate-private-themes] readTheme(${slug}) failed: ${err.message}`)
      process.exit(1)
    }

    const themeFilePath = pkg.themePath(slug)
    let meta
    try {
      meta = JSON.parse(readFileSync(resolve(dirname(themeFilePath), "meta.json"), "utf-8"))
    } catch (err) {
      console.error(`[generate-private-themes] meta.json read failed for ${slug}: ${err.message}`)
      process.exit(1)
    }

    let themeData
    try {
      themeData = engine.generateThemeData(yamlContent)
    } catch (err) {
      console.error(`[generate-private-themes] generateThemeData failed for ${slug}: ${err.message}`)
      process.exit(1)
    }

    const css = adapters.docsAdapter({
      primitives: themeData.primitives,
      tokens: themeData.tokens,
      config: themeData.config,
    })

    // VI-358: every theme's emitted CSS must declare an @font-face for every
    // quoted family it names in `--font-*`, or the browser silently falls
    // back to system-ui on machines without the font installed locally.
    const coverage = engine.validateFontCoverage(css)
    if (coverage.errors.length > 0) {
      for (const e of coverage.errors) {
        console.error(`[generate-private-themes] ${engine.formatFontCoverageError(slug, e.declaredAt, e.family)}`)
      }
      process.exit(1)
    }

    // Hoist @import rules — PostCSS requires them at the top of the file.
    // The pattern matches a full line that starts with `@import` and ends with
    // a trailing `;` — robust against semicolons embedded in URL query strings.
    const cssWithoutImports = css.replace(/^\s*@import\s+.+;\s*$/gm, (match) => {
      importLines.add(match.trim())
      return ""
    })

    cssBlocks.push(`/* ===== ${slug} ===== */\n${cssWithoutImports.trim()}\n`)

    // VI-489: when the theme ships local brand SVGs, copy them into public/ and
    // carry the resolved docs ThemeBrand in the manifest so the Explorer's Brand
    // cohesion view renders the real marks. Themes without a brand/ dir fall
    // through to the Visor default brand at render time (brand omitted here).
    let brand
    if (copyBrandAssets(themeFilePath, slug)) {
      brand = toDocsBrand(engine.resolveThemeBrand(themeData.config.brand).variants, defaultBrandVariants)
    }

    const defaultMode = themeData.config["default-mode"]
    manifest.push({
      slug,
      label: themeData.config.label ?? toLabel(slug),
      group: meta.group ?? "Private",
      typography: extractTypographySlots(themeData.config),
      brand,
      defaultMode,
    })
  }

  manifest.sort((a, b) => {
    if (a.group !== b.group) return a.group.localeCompare(b.group)
    return a.slug.localeCompare(b.slug)
  })

  const importHeader = [...importLines].sort().join("\n")
  const cssOut = `/* generated by scripts/generate-private-themes.mjs — do not edit manually */\n${importHeader ? `${importHeader}\n` : ""}\n${cssBlocks.join("\n\n")}\n`

  const manifestLiteral = manifest
    .map((e) => {
      const base = `slug: ${JSON.stringify(e.slug)}, label: ${JSON.stringify(e.label)}, group: ${JSON.stringify(e.group)}`
      const typo = e.typography ? `, typography: ${JSON.stringify(e.typography)}` : ""
      const brand = e.brand ? `, brand: ${JSON.stringify(e.brand)}` : ""
      const mode = e.defaultMode ? `, defaultMode: ${JSON.stringify(e.defaultMode)}` : ""
      return `  { ${base}${typo}${brand}${mode} },`
    })
    .join("\n")
  const tsOut = `import type { PrivateThemeEntry } from "./private-themes";\n// generated by scripts/generate-private-themes.mjs — do not edit manually\nexport const PRIVATE_THEMES: PrivateThemeEntry[] = [\n${manifestLiteral}\n];\n`

  mkdirSync(dirname(cssOutPath), { recursive: true })
  mkdirSync(dirname(tsOutPath), { recursive: true })
  writeFileSync(cssOutPath, cssOut, "utf-8")
  writeFileSync(tsOutPath, tsOut, "utf-8")
  console.log(`[generate-private-themes] generated ${manifest.length} theme(s): ${manifest.map((e) => e.slug).join(", ")}`)
}

main().catch((err) => {
  console.error(`[generate-private-themes] unexpected error: ${err.stack ?? err.message}`)
  process.exit(1)
})
